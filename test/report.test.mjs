import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, copyFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const bin = join(root, 'bin', 'councilkit');

// A temp dir holding the fixture ledger as slug `add-json`. Golden file pattern: compare the whole
// output to a committed file (fixtures/report-ok.md), regenerated by hand when the format changes.
function fixtureDir(t) {
  const dir = mkdtempSync(join(tmpdir(), 'councilkit-report-'));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  mkdirSync(join(dir, '.councilkit', 'add-json'), { recursive: true });
  const ledger = join(dir, '.councilkit', 'add-json', 'ledger.jsonl');
  copyFileSync(join(root, 'fixtures', 'ledger-ok.jsonl'), ledger);
  const cli = (...args) => spawnSync(process.execPath, [bin, ...args], { cwd: dir, encoding: 'utf8' });
  return { cli, ledger };
}

test('report --md for the fixture ledger equals the golden file', (t) => {
  const { cli } = fixtureDir(t);
  const r = cli('report', '--slug', 'add-json', '--md');
  assert.equal(r.status, 0, r.stderr);
  assert.equal(r.stdout, readFileSync(join(root, 'fixtures', 'report-ok.md'), 'utf8'));
});

test('report prints the chain head and verify: ok, in text and in markdown', (t) => {
  const { cli } = fixtureDir(t);
  const head = 'sha256:83c107d8bd7952fdb89f6cde470b69e134abae726f58f37bf6a526b495e687a6';
  for (const args of [[], ['--md']]) {
    const r = cli('report', '--slug', 'add-json', ...args);
    assert.equal(r.status, 0, r.stderr);
    assert.ok(r.stdout.includes(`chain head: ${head}`), r.stdout);
    assert.match(r.stdout, /verify: ok \(5 lines\)/);
  }
  const text = cli('report', '--slug', 'add-json').stdout;
  assert.doesNotMatch(text, /\\\|/, 'text output does not escape pipes');
  assert.match(text, /uphold Acceptance\|testability/);
});

test('report on a broken ledger exits 3 and names the line', (t) => {
  const { cli, ledger } = fixtureDir(t);
  writeFileSync(ledger, 'not json\n', { flag: 'a' });
  const r = cli('report', '--slug', 'add-json');
  assert.equal(r.status, 3);
  assert.match(r.stderr, /line 6: invalid JSON/);
});

test('report on a slug with no ledger says so and exits 2', (t) => {
  const { cli } = fixtureDir(t);
  const r = cli('report', '--slug', 'nothing-here');
  assert.equal(r.status, 2);
  assert.match(r.stderr, /no ledger/);
});
